int fputc(int ch, FILE *f)
{
  HAL_UART_Transmit(&huart1, (uint8_t *)&ch, 1, HAL_MAX_DELAY);
  return ch;
}

/* 不定长串口接收(DMA + 空闲中断)回调。
 * 收到一帧后:把数据+长度打包进消息,投入串口接收队列,再重启 DMA。
 * 注意:必须先拷贝数据再重启 DMA,否则下一帧会覆盖当前数据。 */
void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t size)
{
  if (huart == &huart1)
  {
    if (size > 0)
    {
      UartRxMsg_t msg;
      if (size > UART_RX_MSG_MAX) size = UART_RX_MSG_MAX;
      memcpy(msg.data, s_Rx1Buf, size);
      msg.len = size;
      /* ISR中投队列:超时必须为0(CMSIS-RTOS2内部走FromISR) */
      osMessageQueuePut(q_Uart1RxMsgHandle, &msg, 0, 0);
    }
    /* 重启下一轮不定长接收 */
    HAL_UARTEx_ReceiveToIdle_DMA(&huart1, s_Rx1Buf, sizeof(s_Rx1Buf));
    __HAL_DMA_DISABLE_IT(&hdma_usart1_rx, DMA_IT_HT);
  }
}
